#include <QList>

// Qt 提供的泛型列表容器。
// 类似于“可以存放很多同类型元素的数组/列表”。
//
// 例如：
//
//     QList<int>
//     QList<QString>
//     QList<ProtocolField>
//
// 本文件后面会使用：
//
//     QList<ProtocolField> fields;
//
// 表示一个协议中包含很多个 ProtocolField。


#include <QString>

// Qt 的字符串类。
//
// 类似于 C++ 标准库中的：
//
//     std::string
//
// 但 QString 专门针对 Qt 设计，
// 对 Unicode、中文、Qt GUI 等支持更方便。
//
// 后面例如：
//
//     QString name;
//     QString type;
//     QString data;


#include <QStringList>

// QStringList 可以理解为：
//
//     QList<QString>
//
// 也就是“字符串列表”。
//
// 例如：
//
//     ["INT", "UINT", "HEX", "STRING"]
//
// 后面的 supportedProtocolTypes()
// 就会返回 QStringList。



// ============================================================
// 全局函数声明
// ============================================================

QStringList supportedProtocolTypes();

// 声明一个函数：
//
//     supportedProtocolTypes()
//
// 参数：无
//
// 返回值：QStringList
//
// 作用：
//     返回当前程序支持的协议字段类型列表。
//
// 例如可能返回：
//
//     DEC
//     INT
//     UINT
//     BIN
//     OCT
//     HEX
//     FLT
//     DBL
//     STRING
//     FLAG
//     ...
//
// 注意：
// 这个函数写在 ProtocolParser 类外面，
// 所以它不是 ProtocolParser 的成员函数，
// 而是一个普通的全局函数。



// ============================================================
// ProtocolField
//
// 表示“协议中的一个字段”。
// ============================================================

struct ProtocolField {

    // --------------------------------------------------------
    // 字段名称
    // --------------------------------------------------------

    QString name;

    // 例如：
    //
    //     "speed"
    //     "temperature"
    //     "deviceId"
    //     "header"
    //
    // 对应 XML 中某一个字段的名字。


    // --------------------------------------------------------
    // 字段类型
    // --------------------------------------------------------

    QString type;

    // 表示这个协议字段属于什么类型。
    //
    // 例如项目可能支持：
    //
    //     INT
    //     UINT
    //     HEX
    //     BIN
    //     STRING
    //     FLAG
    //
    // 后续 DataGenerator 会根据 type
    // 决定这个字段应该如何生成。


    // --------------------------------------------------------
    // 数据类型
    // --------------------------------------------------------

    QString dataType;

    // 和 type 类似，但通常表示更具体的数据类型信息。
    //
    // 例如可能是：
    //
    //     INT8
    //     UINT8
    //     INT16
    //     UINT16
    //
    // 具体含义需要结合 protocolparser.cpp
    // 和 XML 格式一起看。
    //
    // 注意：
    // type 和 dataType 很容易混淆，
    // 两者的准确职责最好看后续实现。


    // --------------------------------------------------------
    // 字段数据
    // --------------------------------------------------------

    QString data;

    // 保存字段预设的数据内容。
    //
    // 例如：
    //
    //     "AA55"
    //     "100"
    //     "hello"
    //
    // 如果 XML 中直接指定了某个字段的值，
    // 通常可能保存在这里。


    // --------------------------------------------------------
    // 数值范围
    // --------------------------------------------------------

    double minValue;
    double maxValue;

    // 表示该字段允许的最小值和最大值。
    //
    // 例如：
    //
    //     minValue = 0
    //     maxValue = 100
    //
    // 那么随机生成字段时，可以限制：
    //
    //     0 <= value <= 100
    //
    // 为什么使用 double？
    //
    // 因为它既可以表示整数：
    //
    //     1
    //     100
    //
    // 也可以表示小数：
    //
    //     1.5
    //     3.14159


    // --------------------------------------------------------
    // 字段长度
    // --------------------------------------------------------

    int length;

    // 表示字段长度。
    //
    // 例如：
    //
    //     length = 4
    //
    // 但这个“4”到底代表：
    //
    //     4 bit
    //     4 byte
    //     4 个字符
    //
    // 需要结合你的 XML 规范和 DataGenerator 实现判断。


    // --------------------------------------------------------
    // 是否选择该字段
    // --------------------------------------------------------

    bool isSelected;

    // bool 只有：
    //
    //     true
    //     false
    //
    // 通常表示该字段是否参与生成或发送。
    //
    // 例如：
    //
    //     if (field.isSelected) {
    //         // 生成这个字段
    //     }


    // --------------------------------------------------------
    // 是否是关键字段
    // --------------------------------------------------------

    bool isKey;

    // 表示这个字段是否被标记为“关键字段”。
    //
    // 具体可能用于：
    //
    //     日志显示
    //     唯一标识
    //     特殊处理
    //     协议检查
    //
    // 精确用途要看后续代码如何读取 isKey。


    // --------------------------------------------------------
    // bit 位置
    // --------------------------------------------------------

    int bitIndex;

    // 表示某个字段位于一个字节/整数中的第几位。
    //
    // 例如一个 FLAG 字段可能只占 1 bit：
    //
    // bit7 bit6 bit5 bit4 bit3 bit2 bit1 bit0
    //                     ↑
    //                  bitIndex
    //
    // 如果：
    //
    //     bitIndex = 3
    //
    // 可能表示使用第 3 位。


    // --------------------------------------------------------
    // 是否为循环结束位置
    // --------------------------------------------------------

    bool loopEnd;

    // 这个字段应该和项目的协议循环结构有关。
    //
    // 例如协议可能支持：
    //
    //     循环开始
    //         field A
    //         field B
    //     循环结束
    //
    // loopEnd == true
    // 可能表示：
    //
    //     “当前字段是某个循环段的结束位置。”
    //
    // 具体规则需要结合 XML 解析代码判断。
};


// ============================================================
// ProtocolDefinition
//
// 表示“整个协议定义”。
// ============================================================

struct ProtocolDefinition {

    QString name;

    // 整个协议的名称。
    //
    // 例如：
    //
    //     "TelemetryProtocol"
    //     "TestProtocol"
    //     "RadarMessage"


    QList<ProtocolField> fields;

    // 一个协议通常不是只有一个字段，
    // 而是由很多 ProtocolField 组成。
    //
    // 所以这里使用：
    //
    //     QList<ProtocolField>
    //
    // 保存所有字段。
    //
    // 可以想象成：
    //
    // ProtocolDefinition
    // │
    // ├── name
    // │
    // └── fields
    //      ├── ProtocolField
    //      ├── ProtocolField
    //      ├── ProtocolField
    //      └── ...
};


// ============================================================
// ProtocolParser 类
//
// 作用：
//     负责读取和解析协议 XML 文件。
//
// 它本身不是协议数据，
// 而是“把 XML 转换为 ProtocolDefinition 的工具”。
// ============================================================

class ProtocolParser
{
public:

    // ========================================================
    // public：
    //
    // 以下成员函数可以被类外部调用。
    // ========================================================


    bool load(const QString &filePath);

    // --------------------------------------------------------
    // 加载并解析 XML 协议文件
    // --------------------------------------------------------
    //
    // 参数：
    //
    //     const QString &filePath
    //
    // 表示 XML 文件路径。
    //
    // 例如：
    //
    //     "C:/protocol/test.xml"
    //
    //
    // 返回：
    //
    //     true  → 加载并解析成功
    //     false → 失败
    //
    //
    // 典型调用：
    //
    //     ProtocolParser parser;
    //
    //     if (parser.load("test.xml")) {
    //         ...
    //     }
    //
    //
    // load() 内部大概率会做：
    //
    //     打开 XML
    //         ↓
    //     检查文件
    //         ↓
    //     检查根节点
    //         ↓
    //     读取 protocol 名字
    //         ↓
    //     遍历 field
    //         ↓
    //     构造 ProtocolField
    //         ↓
    //     保存到 ProtocolDefinition
    //         ↓
    //     保存到 m_definition


    QString lastError() const;

    // --------------------------------------------------------
    // 获取最近一次错误信息
    // --------------------------------------------------------
    //
    // 返回值：
    //
    //     QString
    //
    // 例如：
    //
    //     "无法打开文件"
    //     "XML格式错误"
    //     "根节点必须为 protocol"
    //     "不支持的字段类型"
    //
    //
    // 用法：
    //
    //     if (!parser.load(path)) {
    //         qDebug() << parser.lastError();
    //     }
    //
    //
    // 最后的 const：
    //
    //     QString lastError() const;
    //
    // 表示：
    //
    //     这个函数承诺不会修改当前
    //     ProtocolParser 对象内部的数据。
    //
    // 它只是“读取错误信息”。


    ProtocolDefinition definition() const;

    // --------------------------------------------------------
    // 获取已经解析完成的协议定义
    // --------------------------------------------------------
    //
    // load() 成功后，解析结果会保存在：
    //
    //     m_definition
    //
    // definition() 的作用就是：
    //
    //     把这个解析结果返回给外部。
    //
    //
    // 例如：
    //
    //     ProtocolParser parser;
    //
    //     parser.load("test.xml");
    //
    //     ProtocolDefinition def = parser.definition();
    //
    //
    // 然后可以访问：
    //
    //     def.name
    //
    //     def.fields
    //
    //     def.fields[0].name
    //
    //     def.fields[0].type
    //
    //
    // 最后的 const 同样表示：
    //
    //     调用 definition()
    //     不会修改 parser 自己。


private:

    // ========================================================
    // private：
    //
    // 以下成员只能在 ProtocolParser 类内部直接访问。
    //
    // 外部代码不能：
    //
    //     parser.m_lastError
    //
    // 或：
    //
    //     parser.m_definition
    //
    // 必须通过 public 函数访问。
    // ========================================================


    QString m_lastError;

    // 保存最近一次解析错误。
    //
    // 例如 load() 内部可能：
    //
    //     m_lastError = "根节点必须为 protocol";
    //     return false;
    //
    // 然后外部调用：
    //
    //     parser.lastError();
    //
    // 获取它。


    ProtocolDefinition m_definition;

    // 保存当前已经解析好的完整协议。
    //
    // 数据流：
    //
    // XML文件
    //    ↓
    // load()
    //    ↓
    // 解析
    //    ↓
    // ProtocolDefinition
    //    ↓
    // m_definition
    //
    //
    // 外部通过：
    //
    //     definition()
    //
    // 获取它。
};


